import array as arr
snack1 = {"chips", "juice", "cookies", "chips", "apple"}
snack2 = {"cookies", "sandwich", "juice", "sandwich"}
print("Snack Box 1:", snack1)
print("Snack Box 2:", snack2)
snack1.add("banana")
print("Snack Box 1 after adding banana:", snack1)
commonsnacks = snack1.intersection(snack2)
print("Snacks in both boxes:", commonsnacks)
snackcount = arr.array('i', [4, 6, 3, 5])
print("Snack counts array:", snackcount)
snackcount.insert(0, 2)
snackcount.append(7)
print("Snack counts after adding items:", snackcount)
count_of_5 = snackcount.count(5)
print("Number of times 5 appears:", count_of_5)
snackcount.reverse()
print("Reversed snack counts array:", snackcount)
print("")
